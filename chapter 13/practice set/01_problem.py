# Steps to solve it:
# 1.Create 2 virtual environments in same directory
# 2.activate in 1st environment and do the changes you want
# 3.create a requirement.txt file using pip freeze > requirements.txt
# 4.deactivate 1st env and activate second
# 5.Run command "pip install -r .\requirements.txt" to get all requirements of 1st env to 2nd env 
# 6.now 2nd env will be exact like 1st env