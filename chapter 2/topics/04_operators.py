# AIRTHMETIC OPERATORS ARE + , - , * , /
a = 34
b = 56
c = a + b
print (c)
print (a + b)


# ASSIGNMENT OPERATORS ARE = , += , -= etc.
a = 4-2 # ASSIGN 4-2 IN a
print (a)
b = 9
b += 3 #INCREMENT THE VALUE OF b BY 3 AND THEN ASSIGN IT INTO b
print (b)


# COMPARISON OPERATORS ARE == , < , > , <= , >= , != etc.
a = 7 >= 3
print (a)
