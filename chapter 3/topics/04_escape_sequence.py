# SEQUENCE OF CHARACTERS AFTER BACHLASH "\"

# NEW LINE - \n , FOR TAB SPACE - \t , SINGLEQOUTE - \' , BACKLASH - \\ etc.

a = "my name is shubham\nmy age is 18\ni am studying btech"
print(a)

b = "my name is shubham\tmy age is 18\ti am studying btech"
print(b)

c = "my name is shubham\'my age is 18\'i am studying btech"
print(c)

d = "my name is shubham\\my age is 18\\i am studying btech"
print(d)
